import { ChevronLeft, ChevronRight, FileText, Search } from "lucide-react";
import { useEffect, useState } from "react";
import { Link, useSearchParams } from "react-router";

import { EmptyState, ErrorState, LoadingRows, PageHeader } from "@/components/common";
import { ModeBadge } from "@/components/status";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { useDebounced } from "@/hooks/use-debounced";
import { useReportList } from "@/hooks/use-phase3d";
import { formatDateTime, formatPercent } from "@/lib/format";

const PAGE_SIZE = 12;
const ALL = "all";

export default function ReportsPage() {
  const [params, setParams] = useSearchParams();
  const mode = params.get("mode") ?? ALL;
  const [search, setSearch] = useState(params.get("q") ?? "");
  const q = useDebounced(search.trim());
  const page = (params.get("q") ?? "") !== q ? 1 : Math.max(1, Number(params.get("page") ?? 1) || 1);

  const update = (patch: Record<string, string | null>) => {
    const next = new URLSearchParams(params);
    for (const [k, v] of Object.entries(patch)) {
      if (v === null || v === "" || v === ALL) next.delete(k); else next.set(k, v);
    }
    if (!("page" in patch)) next.delete("page");
    setParams(next, { replace: true });
  };
  useEffect(() => {
    if ((params.get("q") ?? "") !== q) update({ q });
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [q]);

  const list = useReportList({ q: q || undefined, mode: mode === ALL ? undefined : mode, page, page_size: PAGE_SIZE });
  const total = list.data?.total ?? 0;
  const pages = Math.max(1, Math.ceil(total / PAGE_SIZE));
  const filtered = !!(q || mode !== ALL);

  return (
    <>
      <PageHeader title="Reports" description="Reports generated by completed executions. Search covers titles, summaries and full text." />
      <div className="mb-4 flex flex-col gap-2 sm:flex-row sm:items-center">
        <div className="relative flex-1">
          <Search className="pointer-events-none absolute left-2.5 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" />
          <Input value={search} onChange={(e) => setSearch(e.target.value)} placeholder="Search reports…" className="pl-8" aria-label="Search reports" />
        </div>
        <Select value={mode} onValueChange={(v) => update({ mode: v })}>
          <SelectTrigger className="w-full sm:w-32" aria-label="Filter reports by mode"><SelectValue /></SelectTrigger>
          <SelectContent>
            <SelectItem value={ALL}>All modes</SelectItem>
            <SelectItem value="live">Live</SelectItem>
            <SelectItem value="demo">Demo</SelectItem>
          </SelectContent>
        </Select>
      </div>

      {list.error && <ErrorState error={list.error} onRetry={() => list.refetch()} className="mb-4" />}
      {list.isLoading ? <LoadingRows rows={5} /> : total === 0 ? (
        filtered ? (
          <EmptyState icon={Search} title="No matching reports" description="Try a different search or clear the filter."
                      action={<Button variant="outline" onClick={() => { setSearch(""); setParams({}, { replace: true }); }}>Clear filters</Button>} />
        ) : (
          <EmptyState icon={FileText} title="No reports yet" description="A report is generated when an execution completes."
                      action={<Button asChild><Link to="/tasks/new">Start a task</Link></Button>} />
        )
      ) : (
        <>
          <ul className="grid gap-3 lg:grid-cols-2" aria-label="Reports">
            {list.data!.items.map((r) => (
              <li key={r.id}>
                <Card className="h-full gap-0 py-4 transition-colors hover:bg-muted/30">
                  <CardContent className="flex h-full flex-col gap-2 px-4">
                    <div className="flex items-center gap-2 text-xs text-muted-foreground">
                      <ModeBadge mode={r.mode === "demo" ? "demo" : "live"} />
                      <span>{formatDateTime(r.created_at)}</span>
                    </div>
                    <Link to={`/reports/${r.id}`} className="font-medium leading-snug hover:underline">{r.title}</Link>
                    <p className="line-clamp-3 text-sm text-muted-foreground">{r.summary}</p>
                    <div className="mt-auto flex flex-wrap gap-x-4 gap-y-1 pt-1 text-xs text-muted-foreground">
                      <span><span className="tabular text-foreground">{r.source_count}</span> cited source{r.source_count === 1 ? "" : "s"}</span>
                      <span>avg. confidence <span className="tabular text-foreground">{formatPercent(r.avg_confidence)}</span></span>
                      {r.citation_violations > 0 && <span className="text-status-warning">{r.citation_violations} invalid citation(s) removed</span>}
                    </div>
                  </CardContent>
                </Card>
              </li>
            ))}
          </ul>
          <div className="mt-4 flex items-center justify-between text-xs text-muted-foreground">
            <span className="tabular">{(page - 1) * PAGE_SIZE + 1}–{Math.min(page * PAGE_SIZE, total)} of {total}</span>
            <div className="flex items-center gap-1">
              <Button variant="ghost" size="icon" className="size-7" disabled={page <= 1} onClick={() => update({ page: String(page - 1) })} aria-label="Previous page">
                <ChevronLeft className="size-4" />
              </Button>
              <span className="tabular px-1">Page {page} / {pages}</span>
              <Button variant="ghost" size="icon" className="size-7" disabled={page >= pages} onClick={() => update({ page: String(page + 1) })} aria-label="Next page">
                <ChevronRight className="size-4" />
              </Button>
            </div>
          </div>
        </>
      )}
    </>
  );
}
